"""Render a guide as markdown, in the layout of docs/gold/github.md."""

from __future__ import annotations

from .schema import Fact, Guide, Label

LABEL_SUFFIX = {
    Label.TESTED: "Tested",
    Label.SOURCED: "Sourced",
    Label.INFERRED: "Inferred",
    Label.UNCERTAIN: "Uncertain",
}


def fact_line(fact: Fact, *, bullet: str = "-") -> list[str]:
    """One fact, with its evidence underneath when it has any."""
    lines = [f"{bullet} {fact.text} *({LABEL_SUFFIX[fact.label]})*"]
    indent = " " * (len(bullet) + 1)
    if fact.quote and fact.source_url:
        lines.append(f'{indent}> "{fact.quote}" — [source]({fact.source_url})')
    elif fact.source_url:
        lines.append(f"{indent}> [source]({fact.source_url})")
    if fact.note:
        lines.append(f"{indent}> {fact.note}")
    return lines


def inline(label: str, fact: Fact) -> list[str]:
    lines = [f"**{label}:** {fact.text} *({LABEL_SUFFIX[fact.label]})*"]
    if fact.quote and fact.source_url:
        lines.append(f'> "{fact.quote}" — [source]({fact.source_url})')
    elif fact.note:
        lines.append(f"> {fact.note}")
    return lines


def section(title: str, facts: list[Fact], *, numbered: bool = False) -> list[str]:
    if not facts:
        return []
    lines = [f"**{title}**", ""]
    for index, fact in enumerate(facts, start=1):
        lines += fact_line(fact, bullet=f"{index}." if numbered else "-")
    lines.append("")
    return lines


def render(guide: Guide) -> str:
    lines = [f"# {guide.app_name}", "", f"**{guide.app_name}, {guide.website}**", ""]
    lines += inline("Verdict", guide.verdict) + [""]

    lines.append(f"**Difficulty:** {guide.difficulty.value}")
    if guide.difficulty_reason:
        lines.append(f"**Why:** {guide.difficulty_reason.text} "
                     f"*({LABEL_SUFFIX[guide.difficulty_reason.label]})*")
    lines += [
        f"**Hands-on time:** {guide.hands_on_time.text} "
        f"*({LABEL_SUFFIX[guide.hands_on_time.label]})*",
        f"**Waiting time:** {guide.waiting_time.text} "
        f"*({LABEL_SUFFIX[guide.waiting_time.label]})*",
        "",
    ]
    lines += inline("Composio status", guide.composio_status) + [""]

    lines += section("Prerequisites", guide.prerequisites)
    lines += section("Setup steps", guide.setup_steps, numbered=True)
    lines += section("Scopes", guide.scopes)
    lines += section("Limits before approval", guide.limits_before_approval)
    lines += section("Approval process", guide.approval_process)
    lines += section("Likely blockers", guide.likely_blockers)

    if guide.agent_can_do:
        lines += ["**Agent can do**", ""]
        lines += [f"- {item}" for item in guide.agent_can_do] + [""]
    if guide.you_must_do:
        lines += ["**You must do**", ""]
        lines += [f"- {item}" for item in guide.you_must_do] + [""]

    lines += section("Open questions", guide.open_questions)

    if guide.sources:
        lines += ["**Sources**", ""]
        for source in guide.sources:
            if source.url:
                lines.append(f"- [{source.title or source.url}]({source.url})")
            else:
                lines.append(f"- {source.title}")
        lines.append("")

    verified = guide.last_verified
    who = verified.by_name or verified.by
    lines.append(f"**Last verified:** {verified.date}, by {who}"
                 f"{' (' + verified.note + ')' if verified.note else ''}.")
    if guide.meta.model:
        lines.append("")
        lines.append(f"*Generated by Clearance using {guide.meta.model}.*")
    return "\n".join(lines) + "\n"
